"""Build public/index.html and lib/texts.js from src/. Run from anywhere: python3 src/build.py (needs node)."""
import json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
read = lambda p: open(os.path.join(ROOT, p), encoding="utf8").read()

app, content, tgjs = read("src/app.html"), read("src/content.js"), read("src/tg.js")

RANGES = {
    "latin": "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
    "cyrillic": "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116",
}
FAMILIES = {"golos-text": "Golos Text", "unbounded": "Unbounded"}
faces = []
for fn in sorted(os.listdir(os.path.join(ROOT, "public/fonts"))):
    # e.g. golos-text-cyrillic-400-normal.woff2
    stem = fn[: -len("-normal.woff2")]
    rest, weight = stem.rsplit("-", 1)
    fam_key, subset = rest.rsplit("-", 1)
    faces.append(f'@font-face{{font-family:"{FAMILIES[fam_key]}";font-style:normal;font-weight:{weight};'
                 f'font-display:swap;src:url(fonts/{fn}) format("woff2");unicode-range:{RANGES[subset]}}}')

reset = ("<style>:root{color-scheme:light;padding-top:env(safe-area-inset-top);padding-bottom:env(safe-area-inset-bottom)}"
         "body{margin:0;font:14px system-ui,-apple-system,sans-serif}img{max-width:100%}[hidden]{display:none!important}</style>")
head = ('<!doctype html><html lang="ru"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,viewport-fit=cover">'
        '<script src="https://telegram.org/js/telegram-web-app.js?59"></script>' + reset + "</head><body>")
body = (app.replace("/*CONTENT*/", content)
           .replace("<!--FONTS-->", "<style>" + "\n".join(faces) + "</style>")
           .replace("<!--PLATFORM-->", "<script>\n" + tgjs + "\n</script>"))
with open(os.path.join(ROOT, "public/index.html"), "w", encoding="utf8") as f:
    f.write(head + body + "</body></html>")

# Phrases the TTS function serves without login, and AI chat roles for the chat function.
NODE = r'''
const vm=require("vm"),fs=require("fs");
const code=fs.readFileSync(process.argv[1],"utf8")+"\nthis.__o={WORDS_RAW,PHRASES,LESSONS,DIALOGS,SCENARIOS};";
const ctx={};vm.createContext(ctx);vm.runInContext(code,ctx);const o=ctx.__o;
const say=t=>String(t).replace(/\s*\/\s*/g,". ").replace(/…/g,"");
const out=[];
o.WORDS_RAW.trim().split("\n").forEach(l=>{const p=l.split("|");out.push(p[1]);if(p[4])out.push(p[4])});
o.PHRASES.forEach(c=>c.items.forEach(s=>out.push(s.split("|")[0])));
o.LESSONS.forEach(L=>{L.e.forEach(s=>out.push(s.split("|")[0]));L.q.forEach(q=>{if(!Array.isArray(q))out.push(q.b)})});
o.DIALOGS.forEach(d=>d.l.forEach(x=>out.push(x[1])));
console.log(JSON.stringify({texts:[...new Set(out.map(say))],roles:o.SCENARIOS.map(s=>s.role)}));
'''
res = json.loads(subprocess.check_output(["node", "-e", NODE, os.path.join(ROOT, "src/content.js")]))
with open(os.path.join(ROOT, "lib/texts.js"), "w", encoding="utf8") as f:
    f.write("// Generated by src/build.py from src/content.js. Do not edit by hand.\n"
            "// TEXTS: every phrase the app can speak. ROLES: AI chat scenarios, same order as SCENARIOS.\n"
            "export const TEXTS = " + json.dumps(res["texts"], ensure_ascii=False, indent=0) + ";\n"
            "export const ROLES = " + json.dumps(res["roles"], ensure_ascii=False, indent=1) + ";\n")
print(f"built: public/index.html, lib/texts.js ({len(res['texts'])} phrases, {len(res['roles'])} chat scenarios)")
